#!/usr/bin/env python3
"""GVSoC power-hook executable backed by a running 3D-ICE simulation.

GVSoC invokes this program directly for init, update, and final exchanges.
Static component/floorplan mappings come from the architecture-owned system
contract. Per-run paths come from a small hook configuration generated by the
co-simulation launcher.
"""

